CREATE TABLE limite_match_diario (
    id         bigint  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    contador   integer NOT NULL,
    fecha      date    NOT NULL,
    usuario_id bigint  NOT NULL,
    CONSTRAINT limite_match_diario_pkey PRIMARY KEY (id),
    CONSTRAINT uk_limite_match_usuario_fecha UNIQUE (usuario_id, fecha),
    CONSTRAINT fkt824ht2bjd3k79tu18fb526l FOREIGN KEY (usuario_id)
        REFERENCES usuario (id)
);


-- ===========================================================================
-- INVARIANTES QUE NO ESTAN EN EL ESQUEMA
--
-- Dos reglas del modelo se sostienen en la capa de servicio y no en la base de
-- datos. Se dejan escritas aqui para que quien lea el esquema no las eche en
-- falta y las "arregle" anadiendo estructura que no hace falta:
--
-- 1. LOS PARTICIPANTES DE UN CHAT. Son siempre exactamente dos, se deducen del
--    match (quien deslizo, y quien publico lo deslizado) y no cambian nunca en
--    toda la vida del chat. Una tabla CHAT_PARTICIPANTE seria capaz de
--    representar cero, uno o siete participantes, es decir, estados que este
--    dominio no admite, y habria que defenderla con restricciones adicionales
--    para volver a prohibir lo que hoy es imposible por construccion.
--    ChatService.exigirParticipante es el unico punto de entrada al chat y
--    resuelve los dos extremos; las pruebas del bloque 5 lo cubren.
--
-- 2. EL ROL DE LA CUENTA DE UNA PROTECTORA. Nada impide en la base de datos que
--    PROTECTORA.usuario_id apunte a una cuenta con rol CIUDADANO. Lo garantiza
--    AuthService, que crea las dos filas en la misma transaccion.
-- ===========================================================================
