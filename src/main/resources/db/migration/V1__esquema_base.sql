-- Indice espacial. Un B-tree sobre una columna geometry no sirve para nada:
-- ST_DWithin y ST_Distance necesitan GiST, y sin el cada POST /api/alertas
-- (duplicados, RF-25) y cada GET /api/alertas/mapa (RF-04) recorren la tabla
-- entera. @Index de JPA solo genera B-tree, de ahi que hasta ahora viviera en
-- un script aparte (db/indices-postgis.sql) que se ejecutaba en cada arranque.
CREATE INDEX idx_alerta_ubicacion_gist ON alerta USING gist (ultima_ubicacion);


