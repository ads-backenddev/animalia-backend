-- ---------------------------------------------------------------------------
-- MATCH_REGISTRO - un deslizamiento sobre una publicacion (RF-08, RF-09, RF-15)
--
-- publicacion_id es una referencia polimorfica: segun tipo_publicacion apunta a
-- AVISTAMIENTO o a ANIMAL_ADOPCION. Por eso no lleva clave ajena, y por eso las
-- consultas que la usan van SIEMPRE emparejadas con el tipo (ver ChatRepository
-- y CatalogoAdopcionSpec).
-- ---------------------------------------------------------------------------
CREATE TABLE match_registro (
    id               bigint                          NOT NULL
                     GENERATED BY DEFAULT AS IDENTITY,
    created_at       timestamp(6) without time zone  NOT NULL,
    interesado       boolean                         NOT NULL,
    publicacion_id   bigint                          NOT NULL,
    tipo_publicacion character varying(20)           NOT NULL,
    usuario_id       bigint                          NOT NULL,
    CONSTRAINT match_registro_pkey PRIMARY KEY (id),
    CONSTRAINT uk_match_usuario_publicacion
        UNIQUE (usuario_id, publicacion_id, tipo_publicacion),
    CONSTRAINT fkrwmg1i621r7j8787inliarjy6 FOREIGN KEY (usuario_id)
        REFERENCES usuario (id),
    CONSTRAINT match_registro_tipo_publicacion_check
        CHECK (tipo_publicacion IN ('AVISTAMIENTO', 'ADOPCION'))
);


