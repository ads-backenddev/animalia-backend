-- ===========================================================================
-- V1 - Esquema base.
--
-- QUE ES ESTO. Una foto exacta del esquema que hibernate ddl-auto=update habia
-- ido construyendo hasta el bloque de mantenimiento. No introduce ningun
-- cambio: existe para que una base de datos nueva (CI, un companero, Railway)
-- llegue al mismo punto de partida del que arrancan las migraciones
-- siguientes.
--
-- POR QUE EL ORDEN DE LAS COLUMNAS ES RARO. Es el que dejo Hibernate: la clave
-- primaria, luego el resto por orden alfabetico, y al final las claves ajenas.
-- Se respeta —igual que password_changed_at al final de USUARIO, donde quedo al
-- anadirse despues— porque el objetivo de este fichero es reproducir el esquema
-- que ya existe, no uno mas bonito. Cualquier diferencia entre la base de
-- desarrollo y una recien creada deberia ser una senal de que algo va mal, y
-- para eso las dos tienen que ser identicas hasta en lo cosmetico.
--
-- POR QUE LOS NOMBRES DE ALGUNAS RESTRICCIONES SON ILEGIBLES. "fkrwmg1i6..." o
-- "uk5171l57f..." son los que genero Hibernate al crear las claves ajenas y las
-- unicidades que la entidad no bautizo. Se reproducen tal cual por el mismo
-- motivo: la base de datos de desarrollo ya existe con esos nombres y no va a
-- ejecutar este fichero (entra por baseline), asi que inventarles nombres
-- bonitos aqui dejaria una base nueva y la de desarrollo con restricciones
-- distintas para la misma regla. Renombrarlas, si algun dia interesa, es una
-- migracion propia que las cambie en los dos sitios.
--
-- Las restricciones que si tienen nombre legible —uk_match_usuario_publicacion,
-- uk_limite_match_usuario_fecha, los idx_*— son las que las entidades declaran
-- explicitamente con @UniqueConstraint o @Index.
--
-- Los CHECK se escriben con IN (...) y no con = ANY (ARRAY[...]) porque es lo
-- que genera Hibernate a partir de @Enumerated, y PostgreSQL guarda una forma
-- normalizada distinta segun cual de las dos reciba. Con IN, el catalogo de una
-- base nueva queda byte a byte igual que el de la de desarrollo.
-- Se comprobo comparando los pg_dump de las dos.
--
-- V3 usa la otra forma, y no es un descuido: cuando se vio esto, V3 ya estaba
-- aplicada en la base de desarrollo y reescribirla habria cambiado su checksum
-- y roto el arranque. Alli da igual, porque las dos bases SI ejecutan V3 y
-- acaban con la misma normalizacion; en V1 no daba igual, precisamente porque
-- la base de desarrollo no la ejecuta.
-- ===========================================================================

