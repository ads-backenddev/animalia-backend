-- ---------------------------------------------------------------------------
-- LIMITE_MATCH_DIARIO - cuota de matches por usuario y dia (RF-24)
--
-- La unicidad (usuario_id, fecha) no es solo higiene: es el mecanismo de
-- concurrencia con el que MatchService garantiza un unico contador por dia.
--
-- fecha es DATE y debe seguir siendolo: la cuota se cuenta por dia natural, que
