-- ---------------------------------------------------------------------------
-- V19 - LIMITE_AVISTAMIENTO_DIARIO: cupo diario de avistamientos por usuario
-- y alerta
--
-- POST /api/avistamientos no tenia limite. Con el feed reservado al dueno de la
-- alerta, un usuario hostil podia registrar cientos de avistamientos falsos en
-- la alerta de otro, todos con la misma foto: el dueno recibia un
-- NUEVO_AVISTAMIENTO por cada uno, y su feed, que ensena primero los mas
-- recientes en tandas de 30, dejaba enterrado al testigo de verdad.
--
-- POR USUARIO, ALERTA Y DIA NATURAL de Europe/Madrid. Lo que se limita es lo
-- que una persona puede volcar sobre UNA alerta, no a cuantas alertas ayuda.
-- Cinco al dia por defecto (app.avistamientos.limite-diario-por-alerta), de
-- sobra para quien sigue de verdad al animal por el barrio.
--
-- LA MISMA FORMA QUE LIMITE_MATCH_DIARIO (V1) Y LIMITE_FOTO_DIARIO (V15): la
-- restriccion unica permite crear la fila con ON CONFLICT DO NOTHING y sumar
-- con un UPDATE condicional, sin carreras entre peticiones simultaneas. Una
-- tabla propia, y no una columna mas en aquellas, por lo que ya explicaba V15:
-- otra clave —aqui entra la alerta— y otro requisito.
--
-- POR QUE NO CONTAR LOS AVISTAMIENTOS DE HOY, que ya existen: contar antes de
-- insertar deja pasar del limite a dos registros simultaneos, el mismo motivo
-- que en V15.
--
-- fecha es DATE, como en las otras dos: un dia de calendario de Europe/Madrid,
-- no un instante.
-- ---------------------------------------------------------------------------

CREATE TABLE limite_avistamiento_diario (
    id         bigint  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    usuario_id bigint  NOT NULL,
    alerta_id  bigint  NOT NULL,
    fecha      date    NOT NULL,
    contador   integer NOT NULL,
    CONSTRAINT pk_limite_avistamiento_diario PRIMARY KEY (id),
    CONSTRAINT uk_limite_avistamiento_usuario_alerta_fecha UNIQUE (usuario_id, alerta_id, fecha),
    CONSTRAINT fk_limite_avistamiento_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_limite_avistamiento_alerta FOREIGN KEY (alerta_id) REFERENCES alerta (id),
    CONSTRAINT ck_limite_avistamiento_contador CHECK (contador >= 0)
);
