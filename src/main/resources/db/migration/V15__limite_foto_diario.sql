-- ---------------------------------------------------------------------------
-- V15 - LIMITE_FOTO_DIARIO: cupo diario de subidas por usuario
--
-- POST /api/fotos no tenia limite. Un usuario autenticado podia subir fotos
-- sin usarlas hasta llenar el volumen de Railway, que se paga por espacio: la
-- limpieza diaria solo las borra pasado un dia, y para entonces el volumen ya
-- puede estar lleno, o la factura llegar antes de que nadie lo note.
--
-- ES LA MISMA FORMA QUE LIMITE_MATCH_DIARIO (V1, RF-24), y a proposito: un
-- contador por usuario y dia natural, con la restriccion unica que permite
-- crearlo con ON CONFLICT DO NOTHING e incrementarlo con un UPDATE condicional,
-- sin carreras entre peticiones simultaneas.
--
-- POR QUE UNA TABLA NUEVA Y NO AMPLIAR AQUELLA con una columna de tipo: habria
-- que renombrar la tabla y su entidad, que hoy dicen "match", o guardar fotos
-- en una tabla que se llama de matches; y en los dos casos tocar el codigo de
-- RF-24, que no tiene nada que ver con esto.
--
-- POR QUE NO CONTAR LAS FILAS DE FOTO DE HOY, que ya existen: el recuento
-- bajaria al borrarse fotos (cambiar la de perfil borra la anterior), y contar
-- antes de insertar deja pasar del limite a dos subidas simultaneas.
--
-- fecha es DATE, como en LIMITE_MATCH_DIARIO (ver V2): un dia de calendario de
-- Europe/Madrid, no un instante.
-- ---------------------------------------------------------------------------

CREATE TABLE limite_foto_diario (
    id         bigint  NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    usuario_id bigint  NOT NULL,
    fecha      date    NOT NULL,
    contador   integer NOT NULL,
    CONSTRAINT pk_limite_foto_diario PRIMARY KEY (id),
    CONSTRAINT uk_limite_foto_usuario_fecha UNIQUE (usuario_id, fecha),
    CONSTRAINT fk_limite_foto_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_limite_foto_contador CHECK (contador >= 0)
);
